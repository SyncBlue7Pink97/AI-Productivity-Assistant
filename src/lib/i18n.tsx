const DICTS: Record<Lang, Partials> = { en, zu, af, st };

export type TFunc = (
  key: keyof Dict,
  vars?: Record<string, string | number>,
) => string;

type I18nStore = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFunc;
};

const globalRef = globalThis as unknown as {
  __siblingSyncI18nContext?: Context<I18nStore | null>;
};
const I18nContext =
  globalRef.__siblingSyncI18nContext ?? createContext<I18nStore | null>(null);
globalRef.__siblingSyncI18nContext = I18nContext;

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) =>
    k in vars ? String(vars[k]) : m,
  );
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("en");

  const t = useCallback<TFunc>(
    (key, vars) => {
      const dict = DICTS[lang] ?? {};
      const value = dict[key] ?? en[key] ?? String(key);
      return interpolate(value, vars);
    },
    [lang],
  );

  const value = useMemo<I18nStore>(() => ({ lang, setLang, t }), [lang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
